/// @file cx_math.h
/// @brief Constexpr double math with no libm: the transcendentals the compile-time IIR designers need.
// SPDX-License-Identifier: MIT
// Copyright 2026 Timothy Place and the DspTap contributors.
//
// The closed-form recursive designs (iir_design.h: the elliptic two-path
// half-band and the odd-order Chebyshev II) are evaluated at compile time
// (SampleRateTap's docs/IIR_PLAN.md, I4), so they need sqrt, the circular and
// hyperbolic functions, exp and log as constant expressions, which <cmath>
// does not offer before C++26. These are written here in plain C++20 double
// arithmetic: no builtins, no __int128, no long double, so GCC, Clang, MSVC
// and AppleClang evaluate the same source. Their bits rest on each compiler's
// constant evaluator doing IEEE 754 double arithmetic (round to nearest, no
// contraction), which tests/test_iir_constexpr.cpp pins for every compiler CI
// runs, one row for all (srdif's rule: a compiler that needs a second row is
// a finding). Like srdif_trig they use no libm; unlike srdif_trig they work
// in double, not in integers, and they run at compile time (a custom design
// at construction calls the same functions at run time).
//
// Every function is a textbook method (the series and reductions of any
// numerical-analysis text; Dekker 1971 for the exact product):
//   - sqrt: Newton's iteration on the mantissa scaled into [1/4, 1) by an
//     even power of two, then one correction step whose residual x - r^2 is
//     formed exactly from Dekker's two-product (Veltkamp's split), so the
//     result is the correctly rounded root but for rare halfway cases;
//   - sin_pi, cos_pi, tan_pi: sin and cos of pi t for a double t, reduced
//     exactly in t (t mod 2 and the octant are exact operations on the
//     double, Sterbenz's lemma), then the Taylor series of sin or cos on
//     |x| <= pi/4 with x = pi t carried as a double-double (pi split in two);
//     every argument the designers take is a rational multiple of pi;
//   - atan_pi: atan(x) / pi, by two argument halvings
//     atan x = 2 atan(x / (1 + sqrt(1 + x^2))) and the Taylor series;
//   - exp, expm1: x = k ln2 + r with ln2 split hi / lo (Cody and Waite),
//     |r| <= ln2 / 2, expm1(r) by its Taylor series in Horner form, then the
//     exact scaling by 2^k (the exponent field written directly);
//   - log, log1p: x = m 2^e with m in [sqrt(1/2), sqrt 2), log m =
//     2 atanh(f / (2 + f)) with f = m - 1 exact, by the atanh series, plus
//     e ln2 split hi / lo;
//   - sinh, cosh, asinh, acosh from expm1, exp, log and sqrt, each in the
//     form without cancellation for its argument range;
//   - exp10m1(x) = 10^x - 1 through expm1 with x ln10 carried as a
//     double-double (the Chebyshev II's 10^(A/10) - 1 and 10^(rp/10) - 1).
// Accuracy, measured against an mpmath leg at 60 digits and against libm
// (tests/test_cx_math.cpp, the reference values generated by
// tools/iir/gen_cx_reference.py): the pins are stated there, per function.
//
// Domain: finite arguments in the ranges stated per function. A design never
// passes anything else; outside them the functions return a documented
// value (0 for sqrt of a negative, the overflowed infinity for exp, and so
// on), never trap, and stay constant expressions.

#pragma once

#include <bit>
#include <cstdint>
#include <limits>

namespace tap::dsp::detail::cx {

    // pi = k_pi + k_pi_lo (the double nearest pi, and the next 53 bits).
    inline constexpr double k_pi    = 3.141592653589793116;
    inline constexpr double k_pi_lo = 1.2246467991473532e-16;
    // ln2 = k_ln2_hi + k_ln2_lo, k_ln2_hi with its 21 low bits zero, so
    // k * k_ln2_hi is exact for |k| < 2^21 (Cody and Waite's reduction).
    inline constexpr double k_ln2_hi = 6.93147180369123816490e-01;
    inline constexpr double k_ln2_lo = 1.90821492927058770002e-10;
    inline constexpr double k_ln2    = 6.93147180559945286227e-01;
    // ln10 = k_ln10 + k_ln10_lo.
    inline constexpr double k_ln10    = 2.302585092994045901094;
    inline constexpr double k_ln10_lo = -2.1707562233822494e-16;

    constexpr double abs(double x) noexcept {
        return x < 0.0 ? -x : x;
    }

    /// x * 2^e, exact while the result is a normal number (the designers stay
    /// there); scaled in two steps so a subnormal result is rounded once.
    constexpr double ldexp(double x, int e) noexcept {
        if (e > 1023) {
            x *= std::bit_cast<double>(std::uint64_t{2046} << 52); // 2^1023
            e -= 1023;
            if (e > 1023) {
                e = 1023;
            }
        }
        else if (e < -1022) {
            x *= std::bit_cast<double>(std::uint64_t{1} << 52); // 2^-1022
            e += 1022;
            if (e < -1022) {
                e = -1022;
            }
        }
        return x * std::bit_cast<double>(static_cast<std::uint64_t>(e + 1023) << 52);
    }

    /// The exponent e of a positive normal x = m 2^e, m in [1, 2).
    constexpr int exponent(double x) noexcept {
        return static_cast<int>((std::bit_cast<std::uint64_t>(x) >> 52) & 0x7ffu) - 1023;
    }

    /// Dekker's exact product: a * b == hi + lo for |a|, |b| < 2^995 and no
    /// underflow (Veltkamp's split into 26-bit halves).
    struct two_product {
        double hi = 0.0;
        double lo = 0.0;
    };
    constexpr two_product exact_product(double a, double b) noexcept {
        constexpr double split = 134217729.0; // 2^27 + 1
        const double     ca    = split * a;
        const double     a_hi  = ca - (ca - a);
        const double     a_lo  = a - a_hi;
        const double     cb    = split * b;
        const double     b_hi  = cb - (cb - b);
        const double     b_lo  = b - b_hi;
        const double     p     = a * b;
        const double     e     = ((a_hi * b_hi - p) + a_hi * b_lo + a_lo * b_hi) + a_lo * b_lo;
        return {p, e};
    }

    /// sqrt(x) for finite x >= 0 (0 for x <= 0); correctly rounded but for
    /// rare halfway cases (tests/test_cx_math.cpp states the measured error).
    constexpr double sqrt(double x) noexcept {
        if (!(x > 0.0)) {
            return 0.0;
        }
        if (x == std::numeric_limits<double>::infinity()) {
            return x;
        }
        // Normalize: x = m 4^j with m in [1/4, 1), exactly. A subnormal x is
        // first lifted by 2^108.
        int lift = 0;
        if (x < std::numeric_limits<double>::min()) {
            x *= ldexp(1.0, 108);
            lift = 54;
        }
        int e = exponent(x) + 1; // x = m 2^e, m in [1/2, 1)
        if ((e & 1) != 0) {
            ++e; // m in [1/4, 1/2)
        }
        const double m = ldexp(x, -e);
        double       r = 0.5 + 0.5 * m; // within 1/8 of sqrt(m) on [1/4, 1)
        for (int i = 0; i < 6; ++i) {
            r = 0.5 * (r + m / r);
        }
        // One correction from the exact residual m - r^2.
        const two_product rr       = exact_product(r, r);
        const double      residual = (m - rr.hi) - rr.lo;
        r += residual / (2.0 * r);
        return ldexp(r, e / 2 - lift);
    }

    namespace series {

        /// sin x for |x| <= pi/4: Taylor, Horner from the 25th power.
        constexpr double sin(double x) noexcept {
            const double x2 = x * x;
            double       p  = 1.0;
            for (int n = 12; n >= 1; --n) {
                p = 1.0 - x2 / static_cast<double>((2 * n) * (2 * n + 1)) * p;
            }
            return x * p;
        }

        /// cos x for |x| <= pi/4: Taylor, Horner from the 26th power.
        constexpr double cos(double x) noexcept {
            const double x2 = x * x;
            double       p  = 1.0;
            for (int n = 13; n >= 1; --n) {
                p = 1.0 - x2 / static_cast<double>((2 * n - 1) * (2 * n)) * p;
            }
            return p;
        }

        /// sin(pi t) for |t| <= 1/4, pi t as a double-double.
        constexpr double sin_pi_small(double t) noexcept {
            const two_product x  = exact_product(k_pi, t);
            const double      lo = x.lo + k_pi_lo * t;
            // sin(hi + lo) = sin(hi) + lo cos(hi), |lo| below an ulp of hi.
            return sin(x.hi) + lo * (1.0 - 0.5 * x.hi * x.hi);
        }

        /// cos(pi t) for |t| <= 1/4.
        constexpr double cos_pi_small(double t) noexcept {
            const two_product x  = exact_product(k_pi, t);
            const double      lo = x.lo + k_pi_lo * t;
            return cos(x.hi) - lo * x.hi;
        }

    } // namespace series

    /// t - 2 round(t / 2), in [-1, 1], exact for every finite t.
    constexpr double reduce_mod2(double t) noexcept {
        const double h = 0.5 * t; // exact
        if (abs(h) >= 4503599627370496.0) {
            return 0.0; // |t| >= 2^53: t is an even integer
        }
        const auto   n = static_cast<std::int64_t>(h < 0.0 ? h - 0.5 : h + 0.5);
        const double r = t - 2.0 * static_cast<double>(n); // exact: both multiples of ulp(t), |r| <= 1
        return r;
    }

    /// sin(pi t) for finite t.
    constexpr double sin_pi(double t) noexcept {
        double       r    = reduce_mod2(t); // [-1, 1]
        const double sign = r < 0.0 ? -1.0 : 1.0;
        r                 = abs(r);
        if (r > 0.5) {
            r = 1.0 - r; // exact (Sterbenz), sin(pi (1 - r)) = sin(pi r)
        }
        if (r <= 0.25) {
            return sign * series::sin_pi_small(r);
        }
        return sign * series::cos_pi_small(0.5 - r); // exact
    }

    /// cos(pi t) for finite t.
    constexpr double cos_pi(double t) noexcept {
        double r = abs(reduce_mod2(t)); // [0, 1]
        if (r <= 0.25) {
            return series::cos_pi_small(r);
        }
        if (r <= 0.75) {
            return series::sin_pi_small(0.5 - r); // exact
        }
        return -series::cos_pi_small(1.0 - r); // exact
    }

    /// tan(pi t) for finite t away from the poles.
    constexpr double tan_pi(double t) noexcept {
        return sin_pi(t) / cos_pi(t);
    }

    /// atan(x) / pi for finite x, in [-1/2, 1/2].
    constexpr double atan_pi(double x) noexcept {
        const double sign = x < 0.0 ? -1.0 : 1.0;
        x                 = abs(x);
        bool reciprocal   = false;
        if (x > 1.0) {
            x          = 1.0 / x;
            reciprocal = true;
        }
        // Two halvings: atan x = 2 atan(x / (1 + sqrt(1 + x^2))), x <= tan(pi/16).
        for (int i = 0; i < 2; ++i) {
            x = x / (1.0 + sqrt(1.0 + x * x));
        }
        const double x2 = x * x;
        double       p  = 0.0;
        for (int n = 13; n >= 1; --n) {
            p = (n % 2 == 1 ? -1.0 : 1.0) / static_cast<double>(2 * n + 1) + x2 * p;
        }
        p                  = 4.0 * (x + x * x2 * p); // atan of the original reduced x
        const double turns = p / k_pi;
        return sign * (reciprocal ? 0.5 - turns : turns);
    }

    /// e^r - 1 for |r| <= ln2 / 2 + a little: Taylor in Horner form.
    constexpr double expm1_small(double r) noexcept {
        double p = 1.0;
        for (int n = 19; n >= 2; --n) {
            p = 1.0 + r / static_cast<double>(n) * p;
        }
        return r * p;
    }

    /// e^x - 1 for finite x (overflows to infinity past 709.78; -1 below -40).
    constexpr double expm1(double x) noexcept {
        if (x > 709.782712893384) {
            return std::numeric_limits<double>::infinity();
        }
        if (x < -40.0) {
            return -1.0;
        }
        if (abs(x) <= 0.3465735902799726) {
            return expm1_small(x);
        }
        const double t = x / k_ln2;
        const auto   k = static_cast<int>(t < 0.0 ? t - 0.5 : t + 0.5);
        const double r = (x - static_cast<double>(k) * k_ln2_hi) - static_cast<double>(k) * k_ln2_lo;
        const double u = expm1_small(r); // e^x = 2^k (1 + u)
        // e^x - 1 with one rounding where 1 - 2^-k (or 1 - 2^k) is exact.
        if (k > 0 && k <= 52) {
            return ldexp(u + (1.0 - ldexp(1.0, -k)), k);
        }
        if (k < 0 && k >= -53) {
            return ldexp(u, k) - (1.0 - ldexp(1.0, k));
        }
        return ldexp(1.0 + u, k) - 1.0;
    }

    /// e^x for finite x (0 below -745.13, infinity above 709.78).
    constexpr double exp(double x) noexcept {
        if (x > 709.782712893384) {
            return std::numeric_limits<double>::infinity();
        }
        if (x < -745.1332191019412) {
            return 0.0;
        }
        const double t = x / k_ln2;
        const auto   k = static_cast<int>(t < 0.0 ? t - 0.5 : t + 0.5);
        const double r = (x - static_cast<double>(k) * k_ln2_hi) - static_cast<double>(k) * k_ln2_lo;
        return ldexp(1.0 + expm1_small(r), k);
    }

    /// log(1 + f) for |f| <= sqrt 2 - 1 (the reduced mantissa): 2 atanh(s),
    /// s = f / (2 + f), by the atanh series, as f - s (f - R) with R =
    /// 2 s^2 (1/3 + s^2 / 5 + ...): since 2 s = f - s f, the leading term is
    /// the exact f and the rounding falls on the small correction.
    constexpr double log1p_small(double f) noexcept {
        const double s  = f / (2.0 + f);
        const double s2 = s * s;
        double       p  = 0.0;
        for (int n = 13; n >= 1; --n) {
            p = 1.0 / static_cast<double>(2 * n + 1) + s2 * p;
        }
        return f - s * (f - 2.0 * s2 * p);
    }

    /// log(x) for finite x > 0 (-infinity for x <= 0).
    constexpr double log(double x) noexcept {
        if (!(x > 0.0)) {
            return -std::numeric_limits<double>::infinity();
        }
        if (x == std::numeric_limits<double>::infinity()) {
            return x;
        }
        int lift = 0;
        if (x < std::numeric_limits<double>::min()) {
            x *= ldexp(1.0, 54);
            lift = 54;
        }
        int    e = exponent(x);
        double m = ldexp(x, -e); // [1, 2)
        if (m > 1.4142135623730951) {
            m *= 0.5; // exact
            ++e;
        }
        e -= lift;
        const double lm = log1p_small(m - 1.0); // m - 1 exact (Sterbenz)
        const double de = static_cast<double>(e);
        return de * k_ln2_hi + (lm + de * k_ln2_lo);
    }

    /// log(1 + x) for finite x > -1.
    constexpr double log1p(double x) noexcept {
        if (abs(x) <= 0.4142135623730950) {
            return log1p_small(x);
        }
        return log(1.0 + x);
    }

    /// sinh(x) for finite |x| <= 709: (u + u / (u + 1)) / 2 with u = expm1(|x|).
    constexpr double sinh(double x) noexcept {
        const double u = expm1(abs(x));
        const double s = 0.5 * (u + u / (u + 1.0));
        return x < 0.0 ? -s : s;
    }

    /// cosh(x) for finite |x| <= 709.
    constexpr double cosh(double x) noexcept {
        const double e = exp(abs(x));
        return 0.5 * (e + 1.0 / e);
    }

    /// asinh(x) for finite x: log1p(|x| + x^2 / (1 + sqrt(1 + x^2))), the
    /// form without cancellation near 0; log(2|x|) where x^2 would overflow.
    constexpr double asinh(double x) noexcept {
        const double ax = abs(x);
        double       r  = 0.0;
        if (ax > 1e150) {
            r = log(ax) + k_ln2;
        }
        else {
            const double x2 = ax * ax;
            r               = log1p(ax + x2 / (1.0 + sqrt(1.0 + x2)));
        }
        return x < 0.0 ? -r : r;
    }

    /// acosh(x) for finite x >= 1 (0 below): log1p(t + sqrt(t (t + 2))),
    /// t = x - 1 exact near 1; log(2x) where x^2 would overflow.
    constexpr double acosh(double x) noexcept {
        if (!(x > 1.0)) {
            return 0.0;
        }
        if (x > 1e150) {
            return log(x) + k_ln2;
        }
        const double t = x - 1.0;
        return log1p(t + sqrt(t * (t + 2.0)));
    }

    /// 10^x - 1 for finite x, through expm1 with x ln10 a double-double.
    constexpr double exp10m1(double x) noexcept {
        const two_product p  = exact_product(x, k_ln10);
        const double      lo = p.lo + x * k_ln10_lo;
        // e^(hi + lo) - 1 = (e^hi - 1) + e^hi (e^lo - 1), e^lo - 1 ~ lo.
        const double em1 = expm1(p.hi);
        return em1 + (em1 + 1.0) * lo;
    }

    /// 10^x for finite x.
    constexpr double exp10(double x) noexcept {
        return 1.0 + exp10m1(x);
    }

} // namespace tap::dsp::detail::cx
